function question(
  prompt: string,
  correctAnswer: string,
  distractors: [string, string, string],
  explanation: string,
  correctIndex: number,
  hint = "Сопоставьте каждый вариант с определениями и последовательностью из теории.",
): CurriculumQuestion {
  const options = [...distractors];
  options.splice(correctIndex, 0, correctAnswer);
  return { prompt, hint, options, correctIndex, explanation };
}

