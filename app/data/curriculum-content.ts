export function getCurriculumCorrectOptionLabel(moduleId: string, questionPosition: number) {
  const subjectId = moduleId.split("-m")[0] as SourceBasedSubjectId;
  const moduleNumber = Number(moduleId.split("-m")[1]);
  const module = sourceBasedCurriculum[subjectId]?.modules.find(
    (item) => item.number === moduleNumber,
  );
  const question = module?.questions[questionPosition - 1];
  return question ? String.fromCharCode(65 + question.correctIndex) : null;
}
